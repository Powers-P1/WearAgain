export type TranslationKey = keyof typeof en;
const catalogs: Partial<Record<Locale, Record<TranslationKey, string>>> = { en };

/** Incomplete locales fall back to English. Domain/store values are not translated. */
export function t(key: TranslationKey, values?: Record<string, string | number>, locale: Locale = DEFAULT_LOCALE): string {
  const template = catalogs[locale]?.[key] ?? en[key];
  return template.replace(/\{([a-zA-Z]+)\}/g, (_match, token: string) => String(values?.[token] ?? '{' + token + '}'));
}
